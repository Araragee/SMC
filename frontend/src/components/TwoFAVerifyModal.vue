<script setup lang="ts">
import BaseModal from '@components/BaseModal.vue'
import { ref } from 'vue'
import { useAuthStore } from '@stores/auth'

defineProps<{
  isOpen: boolean
}>()

const emit = defineEmits<{
  close: []
  verified: []
}>()

const authStore = useAuthStore()
const code = ref('')
const errorMsg = ref('')
const isVerifying = ref(false)

const handleVerify = async () => {
  if (code.value.length < 6) {
    errorMsg.value = 'Please enter a 6-digit code'
    return
  }
  isVerifying.value = ref(true).value
  errorMsg.value = ''
  try {
    const success = await authStore.verify2FA(code.value)
    if (success) {
      emit('verified')
    }
  } catch (err: any) {
    errorMsg.value = err.response?.data?.detail || err.message || 'Invalid verification code'
  } finally {
    isVerifying.value = false
  }
}

const handleCancel = () => {
  authStore.requires2FA = false
  authStore.challengeToken = null
  emit('close')
}
</script>

<template>
  <BaseModal
    :is-open="isOpen"
    size="md"
    close-label="Cancel verification"
    @close="handleCancel"
  >
    <div class="text-center space-y-2">
      <div
        class="size-16 bg-primary/10 border border-primary/20 rounded-2xl flex items-center justify-center text-primary mx-auto shadow-inner"
      >
        <span class="material-symbols-outlined text-3xl">security</span>
      </div>
      <h2 class="text-2xl font-semibold text-on-surface tracking-tight">
        Two-Factor Verification
      </h2>
      <p class="text-on-surface-variant text-sm font-medium leading-relaxed px-4">
        Enter the verification code generated by your authenticator app to complete sign-in.
      </p>
    </div>

    <form class="space-y-6 mt-6" @submit.prevent="handleVerify">
      <div class="space-y-2">
        <label class="block text-xs uppercase text-on-surface-variant font-bold text-center">
          6-Digit Verification Code
        </label>
        <input
          v-model="code"
          type="text"
          maxlength="8"
          pattern="[0-9]*"
          inputmode="numeric"
          required
          autocomplete="one-time-code"
          placeholder="000000"
          class="input text-center"
          @input="code = code.replace(/[^0-9]/g, '')"
        />
      </div>

      <p v-if="errorMsg" class="text-error text-sm text-center font-bold">{{ errorMsg }}</p>

      <div class="flex gap-4">
        <button type="button" class="btn-ghost flex-1" @click="handleCancel">Cancel</button>
        <button
          type="submit"
          :disabled="isVerifying || code.length < 6"
          class="btn-primary flex-1 gap-2"
        >
          <span v-if="isVerifying" class="material-symbols-outlined animate-spin text-sm"
            >progress_activity</span
          >
          {{ isVerifying ? 'Verifying…' : 'Verify' }}
        </button>
      </div>
    </form>
  </BaseModal>
</template>
